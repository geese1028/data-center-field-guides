#!/usr/bin/env python3
"""
Parse books/KDP-FILL.md into structured JSON catalog for KDP Auto-Filler and Ops Hub.
"""

import re
import json
from pathlib import Path

ROOT = Path("/Users/geese/Downloads/book")
FILL_MD = ROOT / "books" / "KDP-FILL.md"
OUTPUT_JSON = ROOT / "catalog" / "kdp_catalog.json"

GLOBAL_DEFAULTS = {
    "edition_number": "1",
    "author_first_name": "Tristan",
    "author_last_name": "",
    "publishing_rights": "owned",  # I own the copyright
    "adult_content": False,
    "primary_marketplace": "Amazon.com",
    "categories": [
        "Engineering > Industrial, Manufacturing & Operational Systems",
        "Computers & Technology > Hardware > General"
    ],
    "drm": True,
    "publisher": "Data Center Field Guides",
    "kdp_select": False,
    "territories": "worldwide",
    "royalty_rate": "70",
    "price_usd": "12.99",
    "ai_disclosure": {
        "has_ai": True,
        "text": "Entire work, with extensive editing",
        "text_tool": "Grok",
        "images": "Many AI-generated images, with minimal editing",
        "images_tool": "Grok",
        "translations": "Entire work generated by AI",
        "translations_tool": "Grok"
    }
}

def parse():
    text = FILL_MD.read_text(encoding="utf-8")
    sections = re.split(r'\n##\s+', text)
    
    entries = []
    for sec in sections[1:]:
        lines = sec.strip().split('\n')
        header = lines[0].strip()
        if "每本都一样" in header:
            continue
        
        parts = [p.strip() for p in header.split('·')]
        book_label = parts[0] if len(parts) > 0 else ""
        lang_label = parts[1] if len(parts) > 1 else ""
        
        sec_text = '\n'.join(lines[1:])
        
        lang_match = re.search(r'Language 下拉[：:]\s*`?([^`\n]+)`?', sec_text)
        title_match = re.search(r'Book Title[：:]\s*```\n?([^`\n]+)\n?```', sec_text)
        sub_match = re.search(r'Subtitle[：:]\s*```\n?([^`\n]+)\n?```', sec_text)
        desc_match = re.search(r'Description[：:]\s*```\n?([\s\S]*?)\n?```', sec_text)
        kw_match = re.search(r'Keywords[^\n]*[：:]\s*```\n?([\s\S]*?)\n?```', sec_text)
        manuscript_match = re.search(r'Manuscript[：:]\s*`?([^\n`]+)`?', sec_text)
        cover_match = re.search(r'Cover[：:]\s*`?([^\n`]+)`?', sec_text)
        
        keywords = []
        if kw_match:
            keywords = [k.strip() for k in kw_match.group(1).strip().split('\n') if k.strip()]
            
        entry = {
            "key": f"{book_label.replace(' ', '')}_{lang_label}",
            "book_label": book_label,
            "lang_label": lang_label,
            "language_dropdown": lang_match.group(1).strip() if lang_match else lang_label,
            "title": title_match.group(1).strip() if title_match else "",
            "subtitle": sub_match.group(1).strip() if sub_match else "",
            "description": desc_match.group(1).strip() if desc_match else "",
            "keywords": keywords,
            "manuscript_path": manuscript_match.group(1).strip() if manuscript_match else "",
            "cover_path": cover_match.group(1).strip() if cover_match else "",
            "global_defaults": GLOBAL_DEFAULTS
        }
        entries.append(entry)
        
    OUTPUT_JSON.write_text(json.dumps(entries, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Successfully parsed {len(entries)} editions into {OUTPUT_JSON}")

if __name__ == "__main__":
    parse()
